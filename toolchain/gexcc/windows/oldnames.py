#!/usr/bin/env python3
"""oldnames.py MINGW_CRT INCLUDE_MINGW INCLUDE_MINGW_PRE OUT.c: the C runtime's
old names (open for _open, fileno for _fileno and the rest) that mingw-w64's
import libraries give UCRT programs, as functions of gexcc-win's runtime.

mingw-w64 makes them import aliases ("open == _open" in its
lib-common/api-ms-win-crt-*.def); gexcc-win links against Wine's import
libraries, which have none, and wasm-ld has no symbol aliases, so each is a
function calling the new name. The list is mingw-w64's; the prototypes are
the new names' in mingw-w64's headers (clang's AST of them). An old name of
data (environ, timezone ...) is left out, and so is one whose new name takes
variable arguments, except _open and _sopen*, whose optional argument is
one int, the permission mode."""
import glob, json, os, re, subprocess, sys

crt, inc, pre, out = sys.argv[1:5]

aliases = {}
for f in sorted(glob.glob(os.path.join(crt, 'lib-common', 'api-ms-win-crt-*.def*'))):
    for line in open(f):
        m = re.match(r'\s*(\w+)\s*==\s*(\w+)\s*(DATA)?\s*$', line.split(';')[0])
        if m and not m.group(3):
            aliases.setdefault(m.group(1), m.group(2))

HEADERS = ['io.h', 'stdio.h', 'stdlib.h', 'string.h', 'wchar.h', 'process.h', 'direct.h', 'conio.h',
           'math.h', 'time.h', 'malloc.h', 'search.h', 'signal.h', 'fcntl.h', 'locale.h', 'mbstring.h',
           'ctype.h', 'wctype.h', 'memory.h', 'float.h', 'sys/stat.h', 'sys/timeb.h', 'sys/utime.h',
           'sys/locking.h', 'share.h', 'errno.h']
src = '#define NO_OLDNAMES\n#define _CRT_DECLARE_NONSTDC_NAMES 0\n' + ''.join('#include <%s>\n' % h for h in HEADERS)
cmd = ['clang', '--target=x86_64-w64-mingw32', '-xc', '-fsyntax-only', '-Xclang', '-ast-dump=json',
       '-nostdinc', '-isystem', pre, '-isystem', inc,
       '-isystem', subprocess.check_output(['clang', '-print-resource-dir'], text=True).strip() + '/include',
       '-D__GEXW_SDK_X64__', '-D_UCRT', '-U_GNU_SOURCE', '-']
ast = json.loads(subprocess.run(cmd, input=src, capture_output=True, text=True, check=True).stdout)

protos = {}
for d in ast.get('inner', []):
    if d.get('kind') != 'FunctionDecl' or (d.get('name') not in aliases.values() and d.get('name') != '_tzset'):
        continue
    params = [(p.get('name') or 'a%d' % i, p['type']['qualType'])
              for i, p in enumerate(x for x in d.get('inner', []) if x.get('kind') == 'ParmVarDecl')]
    ty = d['type']['qualType']
    ret = ty[:ty.index('(')].strip()
    protos.setdefault(d['name'], (ret, params, d.get('variadic', False) or ', ...)' in ty))


def decl(t, n):
    # a parameter declaration from clang's type spelling (pointers to
    # functions and arrays put the name inside)
    if '(*)' in t:
        return t.replace('(*)', '(*%s)' % n, 1)
    m = re.match(r'(.*?)(\[.*\])$', t)
    return '%s %s%s' % (m.group(1), n, m.group(2)) if m else '%s %s' % (t, n)


body = ['/* generated by oldnames.py from mingw-w64: do not edit */',
        src.replace('#define _CRT_DECLARE_NONSTDC_NAMES 0\n', ''), '#include <stdarg.h>']
made = skipped = 0
for old, new in sorted(aliases.items()):
    if new not in protos or old in protos:
        skipped += 1
        continue
    ret, params, var = protos[new]
    names = ['a%d' % i for i in range(len(params))]
    ps = ', '.join(decl(t, n) for (_, t), n in zip(params, names))
    if var:
        if not re.match(r'_w?sopen|_w?open$', new):
            skipped += 1
            continue
        body.append('%s __cdecl %s(%s, ...) { va_list v; va_start(v, %s); int m = va_arg(v, int); va_end(v); '
                    'return %s(%s, m); }' % (ret, old, ps, names[-1], new, ', '.join(names)))
    else:
        call = '%s(%s)' % (new, ', '.join(names))
        body.append('%s __cdecl %s(%s) { %s%s; }' % (ret, old, ps or 'void', '' if ret == 'void' else 'return ', call))
    made += 1
# The time zone's old names, data mingw-w64's ucrt_tzset.c defines: the
# UCRT's values from tzset() on (the C runtime's initial ones until then)
if 'tzset' not in aliases and '_tzset' in protos:
    body.append('static char gexw_tz0[] = "PST", gexw_tz1[] = "PDT";\n'
                'long timezone = 28800;\nint daylight = 1;\nchar *tzname[2] = { gexw_tz0, gexw_tz1 };\n'
                'void __cdecl tzset(void) { _tzset(); timezone = _timezone; daylight = _daylight; '
                'tzname[0] = _tzname[0]; tzname[1] = _tzname[1]; }')
    made += 1
open(out, 'w').write('\n'.join(body) + '\n')
print('oldnames.py: %d old names, %d left out' % (made, skipped), file=sys.stderr)
