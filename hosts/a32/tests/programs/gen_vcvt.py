# The VFP conversion test program (vcvt.s): VCVT and VCVTR between
# floating-point and integers, between floating-point and fixed-point,
# between single and double precision, and VCVTB/VCVTT to and from half
# precision, over a table of values under each rounding mode,
# Flush-to-zero, Default NaN and the alternative half-precision format;
# each result and the FPSCR after it recorded. `python3 gen_vcvt.py vcvt.s`.
import struct, sys

def f64(x):
    return struct.unpack('<Q', struct.pack('<d', x))[0]

def f32(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]

# (single, double, integer) rows.
SV = [0, 1 << 31, f32(1.0), f32(-1.0), f32(0.5), f32(1.5), f32(2.5), f32(-2.5), f32(-0.5), f32(0.75),
      f32(2147483520.0), f32(2147483648.0), f32(-2147483648.0), f32(4294967040.0), f32(4294967296.0),
      f32(65504.0), f32(65519.0), f32(65520.0), f32(131008.0), f32(2.0 ** -24), f32(2.0 ** -25),
      f32(3 * 2.0 ** -26), f32(2.0 ** -14), f32(6.1e-5), 0x00000001, 0x80400000, 0x7f7fffff,
      0x7f800000, 0xff800000, 0x7fc00001, 0x7f800123, 0xffc12345, f32(1 / 3), f32(-1e10), f32(3.75),
      f32(-32768.5), f32(32767.75), f32(1.0009765625), f32(0.1)]
DV = [0, 1 << 63, f64(1.0), f64(-1.0), f64(0.5), f64(2.5), f64(-2.5), f64(-0.5),
      f64(2147483647.5), f64(2147483648.0), f64(-2147483648.5), f64(4294967295.5), f64(4294967296.0),
      f64(1e300), f64(1e-300), f64(2.0 ** -149), f64(2.0 ** -150), f64(3 * 2.0 ** -151), f64(1 + 2.0 ** -24),
      f64(1 + 2.0 ** -23 + 2.0 ** -50), 0x0000000000000001, 0x7fefffffffffffff, 0x47efffffe0000000,
      0x7ff0000000000000, 0xfff0000000000000, 0x7ff8000000000123, 0x7ff0000000000456, 0xfff8000123456789,
      f64(1 / 3), f64(-1e10), f64(3.75), f64(-32768.5), f64(32767.75), f64(65535.99999), f64(0.1),
      f64(3.4028235677973366e38), f64(-0.0000001), f64(123456789.123), f64(1.17549435e-38)]
IV = [0, 1, 0xffffffff, 0x7fffffff, 0x80000000, 0x01000001, 0x7fffffc0, 0x00fffffe, 0x12345678,
      0x89abcdef, 0x00008000, 0xffff8000, 0x0000ffff, 0x7fff, 0xfffe0001, 0x40000001, 0xc0000001,
      0x00010000, 0x00000003, 0xfffffffd, 0x0000c000, 0x00004000, 0xdeadbeef, 0x00000100, 0x01000000,
      0xfe000001, 0x7ffffff0, 0x80000010, 0x00000007, 0x0000001f, 0x00123456, 0xff00ff00, 0x0f0f0f0f,
      0x55555555, 0xaaaaaaaa, 0x00001000, 0x10000001, 0xfffffff0, 0x00000080]
N = min(len(SV), len(DV), len(IV))
MODES = [0x00000000, 0x00400000, 0x00800000, 0x00c00000, 0x01000000, 0x02000000, 0x04000000, 0x07000000]

out = []
P = out.append
P('@ VFP conversions over a table of values under each rounding mode,')
P('@ Flush-to-zero, Default NaN and the alternative half-precision format:')
P('@ each result and the FPSCR after it recorded.')
P('@ Generated by gen_vcvt.py: `python3 gen_vcvt.py vcvt.s`.')
P('.include "common.inc"')
P('.include "fp.inc"')
P('vectors')
P('reset:')
P('  li sp, STACK_SVC')
P('  li r10, OUT')
P('  fpon')
P('  li r6, modes')
P('1:')
P('  ldr r8, [r6], #4')
P('  li r4, tab')
P('  li r5, tab_end')
P('2:')
P('  ldm r4!, {r0-r3}')
P('  vmov s0, r0')
P('  vmov d1, r1, r2')
P('  vmov s1, r3')
P('  li r11, 0x5a5a5a5a')

def rec_s(r):
    P('  vmrs r9, fpscr')
    P(f'  vmov r0, {r}')
    P('  out r0')
    P('  out r9')

def rec_d(r):
    P('  vmrs r9, fpscr')
    P(f'  vmov r0, r1, {r}')
    P('  out r0')
    P('  out r1')
    P('  out r9')

def op(text, rec, reg, pre=None):
    if pre:
        P(pre)
    P('  vmsr fpscr, r8')
    P(f'  {text}')
    rec(reg)

# Between floating-point and integer.
for t in ['s32', 'u32']:
    op(f'vcvt.{t}.f32 s4, s0', rec_s, 's4')
    op(f'vcvtr.{t}.f32 s4, s0', rec_s, 's4')
    op(f'vcvt.{t}.f64 s4, d1', rec_s, 's4')
    op(f'vcvtr.{t}.f64 s4, d1', rec_s, 's4')
    op(f'vcvt.f32.{t} s4, s1', rec_s, 's4')
    op(f'vcvt.f64.{t} d3, s1', rec_d, 'd3')
# Between floating-point and fixed-point: in place.
for t, fbs in [('s16', [1, 7, 16]), ('u16', [1, 8, 16]), ('s32', [1, 15, 32]), ('u32', [1, 16, 32])]:
    for fb in fbs:
        op(f'vcvt.{t}.f32 s4, s4, #{fb}', rec_s, 's4', '  vmov.f32 s4, s0')
        op(f'vcvt.f32.{t} s4, s4, #{fb}', rec_s, 's4', '  vmov s4, r3')
        op(f'vcvt.{t}.f64 d3, d3, #{fb}', rec_d, 'd3', '  vmov.f64 d3, d1')
        op(f'vcvt.f64.{t} d3, d3, #{fb}', rec_d, 'd3', '  vmov d3, r3, r11')
# Between single and double precision.
op('vcvt.f64.f32 d3, s0', rec_d, 'd3')
op('vcvt.f32.f64 s4, d1', rec_s, 's4')
# Half precision: bottom and top halves, the other half kept.
op('vcvtb.f16.f32 s4, s0', rec_s, 's4', '  vmov s4, r11')
op('vcvtt.f16.f32 s4, s0', rec_s, 's4', '  vmov s4, r11')
op('vcvtb.f32.f16 s4, s1', rec_s, 's4')
op('vcvtt.f32.f16 s4, s1', rec_s, 's4')
op('vcvtb.f32.f16 s4, s0', rec_s, 's4')
P('  cmp r4, r5')
P('  blo 2b')
P('  li r0, modes_end')
P('  cmp r6, r0')
P('  blo 1b')
P('  finish')
P('')
for h in ['undef_handler', 'svc_handler', 'pabt_handler', 'dabt_handler', 'irq_handler', 'fiq_handler']:
    P(f'unexpected {h}')
P('')
P('.align 2')
P('modes:')
for m in MODES:
    P(f'  .word {m:#010x}')
P('modes_end:')
P('tab:')
for k in range(N):
    d = DV[k]
    P(f'  .word {SV[k]:#010x}, {d & 0xffffffff:#010x}, {d >> 32:#010x}, {IV[k]:#010x}')
P('tab_end:')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
