# The ARM data-processing test program (a32_alu.s): every operation under
# a sweep of operands, shifts and carry-in. `python3 gen_alu.py a32_alu.s`;
# tests/qemu.rs writes it into its work directory before assembling it.
import sys
out = []
P = out.append
P('@ ARM data processing, multiplies, saturation and the media instructions')
P('@ over a sweep of operand values and carry-in, each result and the flags')
P('@ after it recorded. Generated by gen_alu.py: `python3 gen_alu.py a32_alu.s`.')
P('.include "common.inc"')
P('vectors')
P('reset:')
P('  li sp, STACK_SVC')
P('  li r10, OUT')
pairs = [(0x80000001, 0x7fffffff), (0, 0), (0xffffffff, 1), (0x12345678, 0x9abcdef0), (0x7fff8000, 0x80007fff)]
shamts = [0, 1, 31, 32, 33, 0xff, 0x101]
def setflags(c):
    P(f'  msr APSR_nzcvqg, #{0x20000000 if c else 0}')
def load(r, v):
    P(f'  li {r}, {v:#x}')
dp = ['adds','adcs','subs','sbcs','rsbs','rscs','ands','eors','orrs','bics']
ops2 = ['r1','r1, lsl #1','r1, lsl #31','r1, lsr #1','r1, lsr #32','r1, asr #32','r1, asr #5','r1, ror #8','r1, rrx',
        'r1, lsl r3','r1, lsr r3','r1, asr r3','r1, ror r3','#0xff000000','#0x3fc','#1']
for a, b in pairs:
    load('r0', a); load('r1', b)
    for s in shamts:
        P(f'  li r3, {s:#x}')
        for c in (0, 1):
            for o in ops2:
                if 'r3' not in o and s != shamts[0]:
                    continue
                for op in dp:
                    setflags(c); P(f'  {op} r2, r0, {o}'); P('  out r2'); P('  outflags')
                for op in ['movs', 'mvns']:
                    setflags(c); P(f'  {op} r2, {o}'); P('  out r2'); P('  outflags')
                for op in ['cmp', 'cmn', 'tst', 'teq']:
                    setflags(c); P(f'  {op} r0, {o}'); P('  outflags')
# conditions: every condition under every flag combination
for nzcv in range(16):
    for cond in ['eq','ne','cs','cc','mi','pl','vs','vc','hi','ls','ge','lt','gt','le','al']:
        P(f'  msr APSR_nzcvq, #{nzcv << 28}')
        P('  mov r2, #0')
        P(f'  mov{cond} r2, #1')
        P(f'  adds{cond} r3, r2, #0')
        P('  out r2'); P('  outflags')
mpairs = [(0x80000000, 0xffffffff), (0, 5), (0x7fff8000, 0x80007fff), (0x12345678, 0x9abcdef0), (0xffff0001, 0x0002ffff), (7, 0)]
for a, b in mpairs:
    load('r0', a); load('r1', b); load('r4', 0x55aa33cc); load('r5', 0x0f0f1234)
    for op in ['mul r2, r0, r1','muls r2, r0, r1','mla r2, r0, r1, r4','mlas r2, r0, r1, r4','mls r2, r0, r1, r4',
               'smulbb r2, r0, r1','smulbt r2, r0, r1','smultb r2, r0, r1','smultt r2, r0, r1',
               'smlabb r2, r0, r1, r4','smlabt r2, r0, r1, r4','smlatb r2, r0, r1, r4','smlatt r2, r0, r1, r4',
               'smulwb r2, r0, r1','smulwt r2, r0, r1','smlawb r2, r0, r1, r4','smlawt r2, r0, r1, r4',
               'smuad r2, r0, r1','smuadx r2, r0, r1','smusd r2, r0, r1','smusdx r2, r0, r1',
               'smlad r2, r0, r1, r4','smladx r2, r0, r1, r4','smlsd r2, r0, r1, r4','smlsdx r2, r0, r1, r4',
               'smmul r2, r0, r1','smmulr r2, r0, r1','smmla r2, r0, r1, r4','smmlar r2, r0, r1, r4','smmls r2, r0, r1, r4','smmlsr r2, r0, r1, r4',
               'sdiv r2, r0, r1','udiv r2, r0, r1','sdiv r2, r1, r0','udiv r2, r1, r0',
               'qadd r2, r0, r1','qsub r2, r0, r1','qdadd r2, r0, r1','qdsub r2, r0, r1',
               'ssat r2, #1, r0','ssat r2, #16, r0, asr #4','ssat r2, #32, r0, lsl #3','ssat r2, #8, r1, asr #32',
               'usat r2, #0, r0','usat r2, #15, r0, lsl #1','usat r2, #31, r1','usat r2, #7, r1, asr #32',
               'ssat16 r2, #4, r0','ssat16 r2, #16, r1','usat16 r2, #0, r0','usat16 r2, #15, r1',
               'usad8 r2, r0, r1','usada8 r2, r0, r1, r4','pkhbt r2, r0, r1','pkhbt r2, r0, r1, lsl #13','pkhtb r2, r0, r1, asr #32','pkhtb r2, r0, r1, asr #7',
               'sxtb r2, r0','sxtb r2, r1, ror #8','sxth r2, r0, ror #16','sxtb16 r2, r1, ror #24','uxtb r2, r0, ror #24','uxth r2, r1','uxtb16 r2, r0, ror #8',
               'sxtab r2, r4, r0','sxtah r2, r4, r1, ror #8','sxtab16 r2, r4, r0, ror #16','uxtab r2, r4, r1','uxtah r2, r4, r0, ror #24','uxtab16 r2, r4, r1',
               'rev r2, r0','rev16 r2, r1','revsh r2, r0','rbit r2, r1','clz r2, r0','clz r2, r1',
               'sbfx r2, r0, #3, #9','ubfx r2, r1, #0, #32','sbfx r2, r1, #31, #1','ubfx r2, r0, #16, #16']:
        P('  msr APSR_nzcvqg, #0')
        P(f'  {op}'); P('  out r2'); P('  outflags')
    for op in ['umull r2, r3, r0, r1','umulls r2, r3, r0, r1','smull r2, r3, r0, r1','smulls r2, r3, r0, r1']:
        P('  msr APSR_nzcvqg, #0'); P(f'  {op}'); P('  out r2'); P('  out r3'); P('  outflags')
    for op in ['umlal','umlals','smlal','smlals','umaal','smlalbb','smlalbt','smlaltb','smlaltt','smlald','smlaldx','smlsld','smlsldx']:
        P('  msr APSR_nzcvqg, #0'); P('  mov r2, r4'); P('  mov r3, r5'); P(f'  {op} r2, r3, r0, r1'); P('  out r2'); P('  out r3'); P('  outflags')
    for p in ['s','q','sh','u','uq','uh']:
        for o in ['add16','asx','sax','sub16','add8','sub8']:
            P('  msr APSR_nzcvqg, #0'); P(f'  {p}{o} r2, r0, r1'); P('  out r2'); P('  outflags')
            P('  sel r2, r4, r5'); P('  out r2')
    P('  mov r2, r4'); P('  bfc r2, #4, #9'); P('  out r2')
    P('  mov r2, r4'); P('  bfi r2, r0, #0, #32'); P('  out r2')
    P('  mov r2, r5'); P('  bfi r2, r1, #13, #7'); P('  out r2')
    P('  movw r2, #0xbeef'); P('  movt r2, #0xdead'); P('  out r2')
P('  finish')
for h in ['undef','svc','pabt','dabt','irq','fiq']:
    P(f'unexpected {h}_handler')
P('.ltorg')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
