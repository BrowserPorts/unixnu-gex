# The VFP data-processing test program (vfp.s): every arithmetic, square
# root, compare and move instruction, single and double precision, over a
# table of operand triples (signed zeros, denormals, the normal limits,
# infinities, quiet and signaling NaNs, rounding ties, random values) under
# each rounding mode, Flush-to-zero and Default NaN; each result and the
# FPSCR after it recorded. `python3 gen_vfp.py vfp.s`.
import struct, sys

def f64(x):
    return struct.unpack('<Q', struct.pack('<d', x))[0]

def f32(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]

class Rng:
    def __init__(self, s):
        self.s = s
    def next(self):
        s = self.s
        s ^= (s >> 12)
        s ^= (s << 25) & (2**64 - 1)
        s ^= (s >> 27)
        self.s = s
        return (s * 0x2545F4914F6CDD1D) & (2**64 - 1)

D = [0, 1 << 63, f64(1.0), f64(-1.0), f64(1.5), f64(3.0), f64(1 / 3), f64(0.1), f64(-2.5),
     0x0010000000000000, 0x8010000000000000, 1, 0x000fffffffffffff, 0x800ffffffffffff1,
     0x7fefffffffffffff, 0xffefffffffffffff, 0x7ff0000000000000, 0xfff0000000000000,
     0x7ff8000000000001, 0x7ff0000000000002, 0xfff8000000000003, 0xfff0000000000004,
     f64(2.0 ** -53), f64(1 + 2.0 ** -52), f64(2.0 ** 1023), f64(1e300), f64(1e-300),
     f64(4.0), f64(2.0 ** -1060), f64(-0.75), f64(1e-310), f64(0.5)]
S = [0, 1 << 31, f32(1.0), f32(-1.0), f32(1.5), f32(3.0), f32(1 / 3), f32(0.1), f32(-2.5),
     0x00800000, 0x80800000, 1, 0x007fffff, 0x807ffff1, 0x7f7fffff, 0xff7fffff,
     0x7f800000, 0xff800000, 0x7fc00001, 0x7f800002, 0xffc00003, 0xff800004,
     f32(2.0 ** -24), f32(1 + 2.0 ** -23), f32(2.0 ** 127), f32(1e38), f32(1e-38),
     f32(4.0), f32(2.0 ** -140), f32(-0.75), f32(1e-40), f32(0.5)]

def triples(vals, n, rng, bits):
    out = []
    for i in range(n):
        pick = lambda: vals[rng.next() % len(vals)] if rng.next() % 4 else rng.next() & ((1 << bits) - 1)
        out.append((pick(), pick(), pick()))
    # Rounding ties and cancellations, exactly.
    if bits == 64:
        out += [(f64(1.0), f64(2.0 ** -53), f64(1.0)), (f64(1.0), f64(3 * 2.0 ** -53), f64(-1.0)),
                (f64(1 + 2.0 ** -52), f64(-1.0), f64(2.0 ** -53)), (f64(0.1), f64(-0.1), f64(0.0))]
    else:
        out += [(f32(1.0), f32(2.0 ** -24), f32(1.0)), (f32(1.0), f32(3 * 2.0 ** -24), f32(-1.0)),
                (f32(1 + 2.0 ** -23), f32(-1.0), f32(2.0 ** -24)), (f32(0.1), f32(-0.1), f32(0.0))]
    return out

MODES = [0x00000000, 0x00400000, 0x00800000, 0x00c00000, 0x01000000, 0x02000000, 0x03c00000, 0x01400000]

out = []
P = out.append
P('@ VFP data processing over a table of operand triples (signed zeros,')
P('@ denormals, the normal limits, infinities, quiet and signaling NaNs,')
P('@ rounding ties, random values) under each rounding mode, Flush-to-zero')
P('@ and Default NaN: each result and the FPSCR after it recorded.')
P('@ Generated by gen_vfp.py: `python3 gen_vfp.py vfp.s`.')
P('.include "common.inc"')
P('.include "fp.inc"')
P('vectors')
P('reset:')
P('  li sp, STACK_SVC')
P('  cps #0x1b')
P('  li sp, STACK_UND')
P('  cps #0x13')
P('  li r10, OUT')
P('  fpon')

def block(prec):
    dp = prec == 'd'
    r = (lambda i: f'd{i}') if dp else (lambda i: f's{i}')
    sfx = '.f64' if dp else '.f32'
    tab = f'tab_{prec}'
    stride = 24 if dp else 12
    P(f'  li r6, modes')
    P(f'1:')
    P(f'  ldr r8, [r6], #4')
    P(f'  li r4, {tab}')
    P(f'  li r5, {tab}_end')
    P(f'2:')
    if dp:
        P('  ldm r4!, {r0-r3}')
        P('  vmov d0, r0, r1')
        P('  vmov d1, r2, r3')
        P('  ldm r4!, {r0, r1}')
        P('  vmov d2, r0, r1')
    else:
        P('  ldm r4!, {r0-r2}')
        P('  vmov s0, r0')
        P('  vmov s1, r1')
        P('  vmov s2, r2')
    def rec():
        P('  vmrs r9, fpscr')
        if dp:
            P('  vmov r0, r1, d3')
            P('  out r0')
            P('  out r1')
        else:
            P('  vmov r0, s3')
            P('  out r0')
        P('  out r9')
    for op in ['vadd', 'vsub', 'vmul', 'vdiv', 'vnmul']:
        P('  vmsr fpscr, r8')
        P(f'  {op}{sfx} {r(3)}, {r(0)}, {r(1)}')
        rec()
    for op in ['vmla', 'vmls', 'vnmla', 'vnmls', 'vfma', 'vfms', 'vfnma', 'vfnms']:
        P(f'  vmov{sfx} {r(3)}, {r(2)}')
        P('  vmsr fpscr, r8')
        P(f'  {op}{sfx} {r(3)}, {r(0)}, {r(1)}')
        rec()
    for op in ['vsqrt', 'vabs', 'vneg', 'vmov']:
        P('  vmsr fpscr, r8')
        P(f'  {op}{sfx} {r(3)}, {r(0)}')
        rec()
    for op in ['vcmp', 'vcmpe']:
        P('  vmsr fpscr, r8')
        P(f'  {op}{sfx} {r(0)}, {r(1)}')
        P('  vmrs r9, fpscr')
        P('  out r9')
        P('  vmsr fpscr, r8')
        P(f'  {op}{sfx} {r(1)}, #0')
        P('  vmrs r9, fpscr')
        P('  out r9')
        # The flags to the APSR, and a conditional operation on them.
        P('  vmrs APSR_nzcv, fpscr')
        P('  outflags')
        P(f'  vmov{sfx} {r(3)}, {r(2)}')
        P(f'  vaddgt{sfx} {r(3)}, {r(0)}, {r(1)}')
        P(f'  vsublt{sfx} {r(3)}, {r(0)}, {r(1)}')
        rec()
    P('  cmp r4, r5')
    P('  blo 2b')
    P('  li r0, modes_end')
    P('  cmp r6, r0')
    P('  blo 1b')

block('s')
block('d')
# VMOV (immediate), and the VFP vector mode, which a core without short
# vector hardware (MVFR0) bounces to support code: UNDEFINED.
for imm in ['1.0', '-0.125', '31.0', '0.1328125']:
    P(f'  vmov.f32 s4, #{imm}')
    P('  vmov r0, s4')
    P('  out r0')
    P(f'  vmov.f64 d5, #{imm}')
    P('  outd 5')
P('  li r0, 0x00010000')
P('  vmsr fpscr, r0')
P('  mov r0, #0')
P('  vadd.f32 s8, s16, s24')
P('  out r0')
P('  mov r0, #0')
P('  vmul.f64 d4, d5, d6')
P('  out r0')
P('  mov r0, #0')
P('  vmov.f32 s8, #1.0')
P('  out r0')
P('  mov r0, #0')
P('  vcmp.f32 s8, s9')
P('  out r0')
P('  li r0, 0x00300000')
P('  vmsr fpscr, r0')
P('  mov r0, #0')
P('  vabs.f32 s8, s9')
P('  out r0')
P('  mov r0, #0')
P('  vmsr fpscr, r0')
P('  vabs.f32 s0, s1')
P('  out r0')
P('  finish')
P('')
P('undef_handler:')
P('  mrs r1, spsr')
P('  out r1')
P('  out lr')
P('  mov r0, #0x99')
P('  movs pc, lr')
P('')
for h in ['svc_handler', 'pabt_handler', 'dabt_handler', 'irq_handler', 'fiq_handler']:
    P(f'unexpected {h}')
P('')
P('.align 2')
P('modes:')
for m in MODES:
    P(f'  .word {m:#010x}')
P('modes_end:')
rng = Rng(0x9e3779b97f4a7c15)
for prec, vals, bits in [('s', S, 32), ('d', D, 64)]:
    P(f'tab_{prec}:')
    for t in triples(vals, 44, rng, bits):
        for v in t:
            if bits == 64:
                P(f'  .word {v & 0xffffffff:#010x}, {v >> 32:#010x}')
            else:
                P(f'  .word {v:#010x}')
    P(f'tab_{prec}_end:')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
